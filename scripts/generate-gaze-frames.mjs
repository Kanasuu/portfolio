#!/usr/bin/env node
/**
 * Generates the cursor-tracking frames for the hero character from ONE portrait.
 *
 * It sends the portrait to Replicate's `fofr/expression-editor` model (LivePortrait),
 * asking for the same face turned/looking in a grid of directions, plus blink, smile and
 * talking-mouth frames. Results are resized and saved to public/character/gaze/ with a
 * manifest.json that the site reads.
 *
 * Usage (PowerShell):
 *   $env:REPLICATE_API_TOKEN = "r8_..."; npm run gaze:generate
 * Options:
 *   --source <path>   portrait to animate (default: character-gaze-source.png, the last frame of the
 *                     intro video, so the switch from video to tracking is seamless; else
 *                     character-reference.png, else public/character.webp)
 *   --cols 7 --rows 5 grid size (default 7×5 = 35 frames)
 *   --flip            mirror the horizontal direction in the manifest (no re-generation)
 *   --only-manifest   rewrite manifest.json from existing frames (use with --flip)
 *
 * Privacy/cost: your portrait is uploaded to Replicate (replicate.com) for processing.
 * Each frame costs about $0.002; the default set is ~40 frames (≈ $0.08).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const OUT = join(ROOT, "public/character/gaze");
const MODEL = "fofr/expression-editor";

const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith("--") ? args[i + 1] : fallback;
};
const flag = (name) => args.includes(`--${name}`);

const cols = Number(opt("cols", 7));
const rows = Number(opt("rows", 5));
const flipX = flag("flip");

// Direction of the grid cell, -1..1. gx: screen left → right, gy: screen top → bottom.
const cellDir = (c, r) => ({ gx: cols === 1 ? 0 : (c / (cols - 1)) * 2 - 1, gy: rows === 1 ? 0 : (r / (rows - 1)) * 2 - 1 });

// Expression-editor parameters for looking toward (gx, gy). Pupils lead, the head follows.
// Ranges: rotate_yaw/pitch ±20, pupil_x/y ±15. If the result looks the wrong way horizontally,
// re-run with --only-manifest --flip instead of regenerating.
const lookParams = ({ gx, gy }) => ({
  rotate_yaw: round(gx * 16),
  rotate_pitch: round(gy * 10),
  pupil_x: round(gx * 11),
  pupil_y: round(gy * 7),
});

const EXTRAS = {
  blink: { blink: -14 },
  smile: { smile: 1.0, eyebrow: 2 },
  talkA: { aaa: 45, smile: 0.25 },
  talkO: { woo: 12, aaa: 15 },
  talkE: { eee: 12, smile: 0.3 },
};

const round = (n) => Math.round(n * 10) / 10;
const frameName = (c, r) => `r${r}c${c}.webp`;

function writeManifest() {
  const frames = [];
  for (let r = 0; r < rows; r++) {
    const row = [];
    for (let c = 0; c < cols; c++) row.push(frameName(flipX ? cols - 1 - c : c, r));
    frames.push(row);
  }
  const extras = Object.fromEntries(Object.keys(EXTRAS).filter((k) => existsSync(join(OUT, `${k}.webp`))).map((k) => [k, `${k}.webp`]));
  const manifest = {
    note: "Generated by scripts/generate-gaze-frames.mjs from Kanasu's portrait via LivePortrait (fofr/expression-editor).",
    cols,
    rows,
    frames, // frames[row][col]: row 0 = looking up, col 0 = looking toward screen left
    extras,
  };
  writeFileSync(join(OUT, "manifest.json"), JSON.stringify(manifest, null, 2));
  console.log(`Wrote ${join(OUT, "manifest.json")}${flipX ? " (horizontally flipped)" : ""}`);
}

async function loadSharp() {
  try {
    return (await import("sharp")).default;
  } catch {
    return null;
  }
}

async function sourceDataUri(sharp) {
  const candidates = [opt("source", ""), join(ROOT, "character-gaze-source.png"), join(ROOT, "character-reference.png"), join(ROOT, "public/character.webp")].filter(Boolean);
  const src = candidates.find((p) => existsSync(p));
  if (!src) throw new Error("No source portrait found. Pass --source <path>.");
  console.log(`Source portrait: ${src}`);
  let buf = readFileSync(src);
  let mime = src.endsWith(".png") ? "image/png" : src.endsWith(".webp") ? "image/webp" : "image/jpeg";
  if (sharp) {
    buf = await sharp(buf).resize({ width: 1280, withoutEnlargement: true }).jpeg({ quality: 92 }).toBuffer();
    mime = "image/jpeg";
  }
  return `data:${mime};base64,${buf.toString("base64")}`;
}

async function run(token, image, params) {
  const res = await fetch(`https://api.replicate.com/v1/models/${MODEL}/predictions`, {
    method: "POST",
    headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json", Prefer: "wait=60" },
    body: JSON.stringify({ input: { image, output_format: "webp", output_quality: 92, ...params } }),
  });
  let prediction = await res.json();
  if (!res.ok) throw new Error(`Replicate error ${res.status}: ${JSON.stringify(prediction)}`);
  while (prediction.status === "starting" || prediction.status === "processing") {
    await new Promise((r) => setTimeout(r, 1500));
    prediction = await (await fetch(prediction.urls.get, { headers: { Authorization: `Bearer ${token}` } })).json();
  }
  if (prediction.status !== "succeeded") throw new Error(`Prediction ${prediction.status}: ${prediction.error ?? ""}`);
  const url = Array.isArray(prediction.output) ? prediction.output[0] : prediction.output;
  return Buffer.from(await (await fetch(url)).arrayBuffer());
}

async function save(sharp, buf, name) {
  // Same size as the hero videos (1280 wide) so frames line up exactly with the video crop.
  const out = sharp ? await sharp(buf).resize({ width: 1280, withoutEnlargement: true }).webp({ quality: 80 }).toBuffer() : buf;
  writeFileSync(join(OUT, name), out);
}

async function main() {
  mkdirSync(OUT, { recursive: true });
  if (flag("only-manifest")) return writeManifest();

  const token = process.env.REPLICATE_API_TOKEN;
  if (!token) {
    console.error("Set REPLICATE_API_TOKEN first (https://replicate.com/account/api-tokens).");
    process.exit(1);
  }
  const sharp = await loadSharp();
  const image = await sourceDataUri(sharp);

  const jobs = [];
  for (let r = 0; r < rows; r++) for (let c = 0; c < cols; c++) jobs.push({ name: frameName(c, r), params: lookParams(cellDir(c, r)) });
  for (const [k, params] of Object.entries(EXTRAS)) jobs.push({ name: `${k}.webp`, params });

  let done = 0;
  const queue = [...jobs];
  const worker = async () => {
    for (let job = queue.shift(); job; job = queue.shift()) {
      if (existsSync(join(OUT, job.name)) && !flag("force")) {
        done++;
        continue;
      }
      for (let attempt = 1; ; attempt++) {
        try {
          await save(sharp, await run(token, image, job.params), job.name);
          break;
        } catch (e) {
          if (attempt >= 3) throw e;
          console.warn(`  retry ${job.name}: ${e.message}`);
          await new Promise((r) => setTimeout(r, 3000 * attempt));
        }
      }
      console.log(`  ${++done}/${jobs.length} ${job.name}`);
    }
  };
  await Promise.all([worker(), worker(), worker()]);
  writeManifest();
  console.log("Done. Restart `npm run dev` so the site picks up the new frames.");
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
