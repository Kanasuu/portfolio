"""
Packs full-size cursor-tracking frames into what the site loads.

Expression edits only change the head, so instead of shipping every frame at full size this
finds the region that differs from the source picture across all frames, crops every frame
to it ("patches") and saves the source once as the base. The site draws the base, then blends
the patches of the nearest poses for smooth movement.

Usage (from the portfolio folder):
    python scripts/pack_gaze_frames.py <frames_dir> --cols 13 --rows 9
    [--source character-gaze-source.png] [--out public/character/gaze]

<frames_dir> holds r{row}c{col}.(png|webp) plus optional blink/smile/talkA/talkO/talkE.
"""

import argparse
import json
from pathlib import Path

from PIL import Image, ImageChops, ImageFilter

EXTRAS = ["blink", "smile", "talkA", "talkO", "talkE"]


def find(frames_dir, stem):
    for ext in ("png", "webp", "jpg"):
        p = frames_dir / f"{stem}.{ext}"
        if p.exists():
            return p
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("frames_dir")
    ap.add_argument("--cols", type=int, required=True)
    ap.add_argument("--rows", type=int, required=True)
    ap.add_argument("--source", default="character-gaze-source.png")
    ap.add_argument("--out", default="public/character/gaze")
    ap.add_argument("--quality", type=int, default=82)
    a = ap.parse_args()

    frames_dir, out = Path(a.frames_dir), Path(a.out)
    base = Image.open(a.source).convert("RGB")
    grid = [[find(frames_dir, f"r{r}c{c}") for c in range(a.cols)] for r in range(a.rows)]
    missing = [f"r{r}c{c}" for r in range(a.rows) for c in range(a.cols) if not grid[r][c]]
    if missing:
        raise SystemExit(f"Missing frames: {', '.join(missing[:8])}{' ...' if len(missing) > 8 else ''}")
    extras = {k: find(frames_dir, k) for k in EXTRAS if find(frames_dir, k)}
    paths = [p for row in grid for p in row] + list(extras.values())

    # Union of changed regions. Blur + threshold ignores compression noise.
    box = None
    for p in paths:
        im = Image.open(p).convert("RGB")
        if im.size != base.size:
            raise SystemExit(f"{p.name} is {im.size}, source is {base.size}")
        diff = ImageChops.difference(im, base).convert("L").filter(ImageFilter.GaussianBlur(2)).point(lambda v: 255 if v > 14 else 0)
        b = diff.getbbox()
        if b:
            box = b if not box else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    if not box:
        raise SystemExit("Frames are identical to the source; nothing to pack.")
    pad = 12
    box = (max(0, box[0] - pad), max(0, box[1] - pad), min(base.width, box[2] + pad), min(base.height, box[3] + pad))
    print(f"Patch region {box} ({box[2] - box[0]}x{box[3] - box[1]} of {base.width}x{base.height})")

    out.mkdir(parents=True, exist_ok=True)
    for old in list(out.glob("*.webp")) + [out / "manifest.json"]:
        if old.exists():
            old.unlink()
    base.save(out / "base.webp", "WEBP", quality=a.quality)
    for p in paths:
        Image.open(p).convert("RGB").crop(box).save(out / f"{p.stem}.webp", "WEBP", quality=a.quality)

    manifest = {
        "note": "Generated by scripts/pack_gaze_frames.py. Patches of Kanasu's picture re-posed with LivePortrait.",
        "cols": a.cols,
        "rows": a.rows,
        "base": "base.webp",
        "patch": {"x": box[0], "y": box[1], "w": box[2] - box[0], "h": box[3] - box[1]},
        "frames": [[f"r{r}c{c}.webp" for c in range(a.cols)] for r in range(a.rows)],  # row 0 = looking up, col 0 = screen left
        "extras": {k: f"{k}.webp" for k in extras},
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2))
    total = sum(f.stat().st_size for f in out.glob("*.webp"))
    print(f"Wrote {len(paths) + 1} images ({total / 1024 / 1024:.1f} MB) and manifest.json to {out}")


if __name__ == "__main__":
    main()
